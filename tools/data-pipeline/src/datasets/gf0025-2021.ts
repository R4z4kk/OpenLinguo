import { err, ok, type Result } from "@openlinguo/core";
import type { Dataset } from "../run.ts";
import { toShards } from "../shards.ts";
import { decodeUtf8, loadReadings, type GradedWord } from "./graded.ts";

// OCR of the official GF0025-2021 PDF (moe.gov.cn, scanned, no restriction) by Pleco Inc.
const COMMIT = "7f3d4fdcfcb6e826001df062747c943d1fa8160e";
const BASE = `https://raw.githubusercontent.com/elkmovie/hsk30/${COMMIT}`;
const VERSION = `GF0025-2021, elkmovie/hsk30@${COMMIT.slice(0, 7)}`;
const LICENSE = "MIT transcription (Pleco Inc.) of the GF0025-2021 standard";
// Counts set by the standard: 11,092 words, 3,000 recognition characters, 1,200 handwriting characters.
const WORD_SECTIONS = ["一", "二", "三", "四", "五", "六", "七一九"].map(
  (band) => `${band}级词汇表`,
);
const WORD_COUNTS = [500, 772, 973, 1000, 1071, 1140, 5636];
const CHARACTER_SECTIONS = [
  ...["一", "二", "三", "四", "五", "六", "七一九"].map((band) => `${band}级汉字表`),
  ...["初等", "中等", "高等"].map((band) => `${band}手写字表`),
];
const CHARACTER_COUNTS = [300, 300, 300, 300, 300, 300, 1200, 300, 400, 500];
const RECOGNITION_SECTIONS = 7;
const SHARD_SIZE = 10_000;

type Item = { readonly section: number; readonly text: string };
type Numbered = { readonly items: readonly Item[]; readonly repairs: readonly string[] };

/** Numbered lines grouped under the expected section titles, in order. */
export const parseNumberedList = (
  text: string,
  sections: readonly string[],
  counts: readonly number[],
): Result<Numbered, string> => {
  const lines = text
    .replace(/\r\n/gu, "\n")
    .split("\n")
    .filter((line) => line.trim() !== "" && !line.startsWith("#"));
  const items: Item[] = [];
  const repairs: string[] = [];
  let section = -1;
  let previous = 0;
  for (const [index, line] of lines.entries()) {
    if (line === sections[section + 1]) {
      section += 1;
      previous = 0;
      continue;
    }
    const match = /^(\d+)\s+(\S.*)$/u.exec(line);
    if (match?.[1] == null || match[2] == null || section < 0) {
      return err(`unexpected line: ${line}`);
    }
    const number = Number(match[1]);
    if (number !== previous + 1) {
      const next = /^(\d+)\s/u.exec(lines[index + 1] ?? "")?.[1];
      if (next == null || Number(next) !== previous + 2) {
        return err(`numbering breaks at "${line}" after ${String(previous)}`);
      }
      repairs.push(`${sections[section] ?? ""}\t${line}\tread as ${String(previous + 1)}`);
    }
    previous += 1;
    items.push({ section, text: match[2].trim() });
  }
  const found = counts.map((_, index) => items.filter((item) => item.section === index).length);
  if (section !== sections.length - 1 || found.some((count, index) => count !== counts[index])) {
    return err(`counts per section ${found.join("/")} differ from ${counts.join("/")}`);
  }
  return ok({ items, repairs });
};

/** Headword forms of a list entry: part of speech, homograph marks and ellipses removed, variants split. */
export const entryForms = (entry: string): readonly string[] =>
  entry
    .replace(/[（(][^）)]*[）)]/gu, "")
    .replace(/[¹²³⁴]/gu, "")
    .replace(/…/gu, "")
    .split(/[｜|]/u)
    .map((form) => form.trim())
    .filter((form) => form !== "");

const repairsTsv = (repairs: readonly string[]): string =>
  `${["section\tline\trepair", ...repairs].join("\n")}\n`;

const readme = (kind: string, summary: string): string => `# GF0025-2021 — ${kind}

Generated by \`tools/data-pipeline\`. Do not edit by hand.

- Source: 国际中文教育中文水平等级标准 (GF0025-2021), Ministry of Education and State Language Commission of the PRC, in force since 2021-07-01, official PDF at http://www.moe.gov.cn/jyb_xwfb/gzdt_gzdt/s5987/202103/t20210329_523304.html
- Transcription used: https://github.com/elkmovie/hsk30 at commit ${COMMIT} (OCR by Pleco Inc., MIT)
- Content: only the factual word → level and character → level mapping
- Levels: 1–6, and 7 for the 7-9 band. This is the national standard, not the HSK 2025 exam syllabus
- Result: ${summary}.
`;

export const gf0025Chars: Dataset = {
  id: "gf0025-2021-chars",
  url: `${BASE}/charlist.txt`,
  license: LICENSE,
  maxAgeDays: 365,
  build: (raw) => {
    const text = decodeUtf8(raw);
    if (!text.ok) return text;
    const parsed = parseNumberedList(text.value, CHARACTER_SECTIONS, CHARACTER_COUNTS);
    if (!parsed.ok) return parsed;
    const recognition = parsed.value.items.filter((item) => item.section < RECOGNITION_SECTIONS);
    const invalid = parsed.value.items.filter((item) => Array.from(item.text).length !== 1);
    if (invalid.length > 0) return err(`not a single character: ${invalid[0]?.text ?? ""}`);
    if (new Set(recognition.map((item) => item.text)).size !== recognition.length) {
      return err("duplicate recognition character");
    }
    const rows = recognition.map((item) => [item.text, item.section + 1] as const);
    const summary = `${String(rows.length)} recognition characters (${CHARACTER_COUNTS.slice(0, RECOGNITION_SECTIONS).join(" / ")}), ${String(parsed.value.repairs.length)} numbering repairs`;
    const files = new Map(toShards("characters", rows, SHARD_SIZE));
    files.set("README.md", readme("recognition characters", summary));
    files.set("repairs.tsv", repairsTsv(parsed.value.repairs));
    return ok({ version: VERSION, files, summary });
  },
};

export const gf0025Words: Dataset = {
  id: "gf0025-2021-words",
  url: `${BASE}/wordlist.txt`,
  license: LICENSE,
  maxAgeDays: 365,
  build: async (raw, readShards) => {
    const text = decodeUtf8(raw);
    if (!text.ok) return text;
    const parsed = parseNumberedList(text.value, WORD_SECTIONS, WORD_COUNTS);
    if (!parsed.ok) return parsed;
    const readings = await loadReadings(readShards, "gf0025-2021-words");
    if (!readings.ok) return readings;

    const levels = new Map<string, Set<number>>();
    for (const item of parsed.value.items) {
      const forms = entryForms(item.text);
      if (forms.length === 0) return err(`empty entry: ${item.text}`);
      for (const form of forms)
        levels.set(form, (levels.get(form) ?? new Set()).add(item.section + 1));
    }
    const issues: string[] = [];
    const rows: GradedWord[] = [...levels].map(([word, set]) => {
      const [lowest = 0, ...others] = [...set].sort((a, b) => a - b);
      const candidates = readings.value.get(word) ?? [];
      if (candidates.length !== 1) {
        const issue = candidates.length === 0 ? "absent" : "polyphone-without-pinyin";
        issues.push(
          `${word}\t${candidates.map((candidate) => candidate.reading).join(" | ")}\t${issue}`,
        );
      }
      return [word, lowest, others, candidates.map((candidate) => candidate.key)];
    });
    const count = (issue: string) => issues.filter((line) => line.endsWith(`\t${issue}`)).length;
    const summary = `${String(rows.length)} headwords from ${String(parsed.value.items.length)} entries, ${String(count("absent"))} absent from CC-CEDICT, ${String(count("polyphone-without-pinyin"))} polyphones graded on every reading, ${String(parsed.value.repairs.length)} numbering repairs`;
    const files = new Map(toShards("words", rows, SHARD_SIZE));
    files.set("README.md", readme("words", summary));
    files.set("issues.tsv", `${["word\tcc_cedict_readings\tissue", ...issues].join("\n")}\n`);
    files.set("repairs.tsv", repairsTsv(parsed.value.repairs));
    return ok({ version: VERSION, files, summary });
  },
};
