import { err, ok, type Result } from "@openlinguo/core";
import { parseNumbered } from "@openlinguo/lang-zh";
import type { Dataset } from "../run.ts";
import { toShards } from "../shards.ts";
import { decodeUtf8, loadReadings, type Candidate } from "./graded.ts";

// Transcription of the official syllabus PDF (copy-protected, so not parsed here); decision 2026-10-09.
const COMMIT = "36c0d11347b5d4caea52917d1262404824ad58d5";
const BASE = `https://raw.githubusercontent.com/harukicoder/hsk30/${COMMIT}/corpus/syllabus2025`;
const VERSION = `2025-11 syllabus, harukicoder/hsk30@${COMMIT.slice(0, 7)}`;
const LICENSE = "MIT transcription of CLEC/CTI syllabus facts";
// Counts published with the syllabus (3,088 recognition characters, per-level maxima) and by the transcription.
const CHARACTER_COUNTS = [246, 125, 284, 441, 431, 413, 1148];
const DISTINCT_WORDS = 10_896;
const SHARD_SIZE = 10_000;

const tsvRows = (text: string, header: string): Result<readonly string[][], string> => {
  const [first, ...lines] = text.replace(/\r\n/gu, "\n").trimEnd().split("\n");
  if (first !== header) return err(`unexpected header: ${String(first)}`);
  return ok(lines.map((line) => line.split("\t")));
};

const level = (value: string): number | null => (/^[1-7]$/u.test(value) ? Number(value) : null);

const readme = (kind: string, summary: string): string => `# HSK 2025 syllabus — ${kind}

Generated by \`tools/data-pipeline\`. Do not edit by hand.

- Source: 新版HSK考试大纲 (HSK Examination Syllabus), Center for Language Education and Cooperation / Chinese Testing International, November 2025
- Transcription used: https://github.com/harukicoder/hsk30 at commit ${COMMIT} (MIT); the official PDF forbids text extraction, so it is not parsed here
- Content: only the factual word → level and character → level mapping; no editorial content of the syllabus
- Levels: 1–6, and 7 for the 7-9 band
- Takedown: on request from the issuing body, see data/SOURCES.md
- Result: ${summary}.
`;

export const hsk2025Chars: Dataset = {
  id: "hsk-2025-chars",
  url: `${BASE}/syllabus2025_chars.tsv`,
  license: LICENSE,
  maxAgeDays: 365,
  build: (raw) => {
    const text = decodeUtf8(raw);
    if (!text.ok) return text;
    const rows = tsvRows(text.value, "character\tlevel");
    if (!rows.ok) return rows;
    const counts = CHARACTER_COUNTS.map(() => 0);
    const seen = new Set<string>();
    const output: (readonly [string, number])[] = [];
    for (const [character = "", value = ""] of rows.value) {
      const rank = level(value);
      if (rank === null || Array.from(character).length !== 1 || seen.has(character)) {
        return err(`invalid character row: ${character}\t${value}`);
      }
      seen.add(character);
      counts[rank - 1] = (counts[rank - 1] ?? 0) + 1;
      output.push([character, rank]);
    }
    if (counts.some((count, index) => count !== CHARACTER_COUNTS[index])) {
      return err(
        `character counts per level ${counts.join("/")} differ from ${CHARACTER_COUNTS.join("/")}`,
      );
    }
    const summary = `${String(output.length)} recognition characters (${counts.join(" / ")})`;
    const files = new Map(toShards("characters", output, SHARD_SIZE));
    files.set("README.md", readme("recognition characters", summary));
    return ok({ version: VERSION, files, summary });
  },
};

const TONE_MARKS = ["̄", "́", "̌", "̀"];

/** Base letters of a diacritic pinyin string, with the tone mark found after each letter. */
const lettersWithTones = (pinyin: string): { letters: string; tones: (number | null)[] } => {
  let letters = "";
  const tones: (number | null)[] = [];
  for (const char of pinyin.normalize("NFD").toLowerCase()) {
    const tone = TONE_MARKS.indexOf(char);
    if (tone >= 0 && tones.length > 0) tones[tones.length - 1] = tone + 1;
    else if (/[a-z]/u.test(char)) {
      letters += char;
      tones.push(null);
    }
  }
  return { letters, tones };
};

/** Number of tolerated tone differences (一/不 sandhi, neutral tone), or null when the reading does not fit. */
const toleratedTones = (word: string, pinyin: string, candidate: Candidate): number | null => {
  const tokens = parseNumbered(candidate.reading);
  if (!tokens.ok) return null;
  const target = lettersWithTones(pinyin);
  const characters = Array.from(word);
  let offset = 0;
  let tolerated = 0;
  for (const [index, token] of tokens.value.entries()) {
    const letters = (token.kind === "syllable" ? token.letters : token.text)
      .toLowerCase()
      .replace(/ü/gu, "u");
    if (target.letters.slice(offset, offset + letters.length) !== letters) return null;
    if (token.kind === "syllable") {
      const marked = target.tones
        .slice(offset, offset + letters.length)
        .find((tone) => tone !== null);
      const tone = marked ?? 5;
      if (tone !== token.tone) {
        const sandhi =
          characters.length === tokens.value.length && /[一不]/u.test(characters[index] ?? "");
        if (!sandhi && tone !== 5 && token.tone !== 5) return null;
        tolerated += 1;
      }
    }
    offset += letters.length;
  }
  return offset === target.letters.length ? tolerated : null;
};

type Resolution =
  | { readonly keys: readonly string[]; readonly issue: null }
  | { readonly keys: readonly string[]; readonly issue: "pinyin-unusable" | "tone-ambiguous" }
  | { readonly keys: readonly []; readonly issue: "absent" };

export const resolveReadings = (
  word: string,
  pinyin: string,
  candidates: readonly Candidate[],
): Resolution => {
  if (candidates.length === 0) return { keys: [], issue: "absent" };
  if (candidates.length === 1)
    return { keys: candidates.map((candidate) => candidate.key), issue: null };
  const scored = candidates.map((candidate) => ({
    key: candidate.key,
    tolerated: toleratedTones(word, pinyin, candidate),
  }));
  const fitting = scored.filter((entry) => entry.tolerated !== null);
  const best = Math.min(...fitting.map((entry) => entry.tolerated ?? Infinity));
  const chosen = fitting.filter((entry) => entry.tolerated === best);
  if (chosen.length === 1) return { keys: chosen.map((entry) => entry.key), issue: null };
  return {
    keys: (chosen.length > 0 ? chosen : scored).map((entry) => entry.key),
    issue: chosen.length > 0 ? "tone-ambiguous" : "pinyin-unusable",
  };
};

export const hsk2025Words: Dataset = {
  id: "hsk-2025-words",
  url: `${BASE}/syllabus2025_words.tsv`,
  license: LICENSE,
  maxAgeDays: 365,
  build: async (raw, readShards) => {
    const text = decodeUtf8(raw);
    if (!text.ok) return text;
    const rows = tsvRows(text.value, "word\tlevel\talso\tpinyin\tpos");
    if (!rows.ok) return rows;
    const readings = await loadReadings(readShards, "hsk-2025-words");
    if (!readings.ok) return readings;

    const seen = new Set<string>();
    const output: (readonly [string, number, readonly number[], readonly string[]])[] = [];
    const issues: string[] = [];
    for (const [word = "", value = "", also = "", pinyin = ""] of rows.value) {
      const rank = level(value);
      const others = also === "" ? [] : also.split(",").map(level);
      if (
        rank === null ||
        word === "" ||
        seen.has(word) ||
        others.some((other) => other === null || other <= rank)
      ) {
        return err(`invalid word row: ${word}\t${value}\t${also}`);
      }
      seen.add(word);
      const resolution = resolveReadings(word, pinyin, readings.value.get(word) ?? []);
      if (resolution.issue !== null) {
        const candidates = (readings.value.get(word) ?? []).map((candidate) => candidate.reading);
        issues.push(`${word}\t${pinyin}\t${candidates.join(" | ")}\t${resolution.issue}`);
      }
      output.push([word, rank, others.filter((other) => other !== null), resolution.keys]);
    }
    if (output.length !== DISTINCT_WORDS) {
      return err(
        `expected ${String(DISTINCT_WORDS)} distinct words, parsed ${String(output.length)}`,
      );
    }
    const counts = [1, 2, 3, 4, 5, 6, 7].map(
      (rank) => output.filter(([, lowest]) => lowest === rank).length,
    );
    const byIssue = (issue: string) => issues.filter((line) => line.endsWith(`\t${issue}`)).length;
    const summary = `${String(output.length)} words by lowest level (${counts.join(" / ")}), ${String(byIssue("absent"))} absent from CC-CEDICT, ${String(byIssue("tone-ambiguous"))} tone-ambiguous and ${String(byIssue("pinyin-unusable"))} with unusable pinyin (level kept on every candidate reading)`;
    const files = new Map(toShards("words", output, SHARD_SIZE));
    files.set("README.md", readme("words", summary));
    files.set(
      "issues.tsv",
      `${["word\tsyllabus_pinyin\tcc_cedict_readings\tissue", ...issues].join("\n")}\n`,
    );
    return ok({ version: VERSION, files, summary });
  },
};
