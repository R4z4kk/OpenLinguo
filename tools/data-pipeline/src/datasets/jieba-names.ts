import { err, ok, parseWith, type Result } from "@openlinguo/core";
import { z } from "zod";
import type { Dataset, ShardReader } from "../run.ts";
import { payloadOf, toShards } from "../shards.ts";
import { decodeUtf8 } from "./graded.ts";
import { countBy, HAN, tsv } from "./wiktextract.ts";

const COMMIT = "67fa2e36e72f69d9134b8a1037b83fbb070b9775";
const VERSION = `fxsjy/jieba@${COMMIT.slice(0, 7)}`;
const LICENSE = "jieba-MIT.txt";
const SHARD_SIZE = 10_000;

export type NameKind = "person" | "place" | "organization" | "name";

/** jieba's proper-name tags (ICTCLAS tag set) and what the reader may call them. */
const KINDS: ReadonlyMap<string, NameKind> = new Map([
  ["nr", "person"],
  ["nrfg", "person"],
  ["ns", "place"],
  ["nt", "organization"],
  // `nrt` holds transliterated names of people and places alike, `nz` any other proper name.
  ["nrt", "name"],
  ["nz", "name"],
]);

/** `[word, kind]`: a proper name of jieba's dictionary that no shipped lexicon has. */
export type NameRow = readonly [string, NameKind];

export type Issue = { readonly word: string; readonly kind: "non-han-title"; readonly tag: string };

export type NamesRelease = {
  readonly rows: readonly NameRow[];
  readonly issues: readonly Issue[];
  readonly tags: ReadonlyMap<string, number>;
  readonly known: number;
};

/** Datasets whose written forms the reader looks up before this signal. */
const LEXICONS = ["cc-cedict", "cfdict", "wiktionary-fr-zh", "wiktionary-zh"] as const;

/** Entries `[simplified, traditional, …]` and gloss rows `[simplified, reading, glosses]`. */
const LexiconRow = z.union([
  z.tuple([z.string(), z.string(), z.array(z.string())]).transform(([simplified]) => [simplified]),
  z
    .tuple([z.string(), z.string(), z.string(), z.array(z.string())])
    .transform(([simplified, traditional]) => [simplified, traditional]),
  z
    .tuple([z.string(), z.string(), z.string(), z.string(), z.array(z.string())])
    .transform(([simplified, traditional]) => [simplified, traditional]),
]);

/** Simplified and traditional forms of every lexicon the reader consults first. */
export const loadKnownForms = async (
  readShards: ShardReader,
): Promise<Result<ReadonlySet<string>, string>> => {
  const forms = new Set<string>();
  for (const dataset of LEXICONS) {
    const shards = await readShards(dataset);
    if (!shards.ok) return err(`cannot read ${dataset}: ${shards.error}`);
    if (shards.value.length === 0) return err(`${dataset} must be built before jieba-names`);
    for (const shard of shards.value) {
      let json: unknown;
      try {
        json = JSON.parse(shard);
      } catch (error) {
        return err(`invalid ${dataset} shard: ${String(error)}`);
      }
      const rows = parseWith(z.array(LexiconRow), json);
      if (!rows.ok) return err(`invalid ${dataset} shard structure`);
      for (const row of rows.value) for (const form of row) forms.add(form);
    }
  }
  return ok(forms);
};

const compareRows = ([a, aKind]: NameRow, [b, bKind]: NameRow): number =>
  a === b ? (aKind < bKind ? -1 : aKind > bKind ? 1 : 0) : a < b ? -1 : 1;

/** The name-tagged words of jieba's `dict.txt` (`word frequency tag` lines) no lexicon has. */
export const parseJiebaDict = (
  text: string,
  known: ReadonlySet<string>,
): Result<NamesRelease, string> => {
  const rows = new Map<string, NameRow>();
  const issues: Issue[] = [];
  const tags = new Map<string, number>();
  let inLexicons = 0;
  const lines = text.split("\n");
  if (lines.at(-1) === "") lines.pop();
  for (const [index, line] of lines.entries()) {
    const fields = line.split(" ");
    const [word = "", frequency = "", tag = ""] = fields;
    if (fields.length !== 3 || word === "" || !/^\d+$/u.test(frequency) || tag === "") {
      return err(`line ${String(index + 1)} is not "word frequency tag": ${line}`);
    }
    const kind = KINDS.get(tag);
    if (kind == null) continue;
    if (known.has(word)) {
      inLexicons += 1;
      continue;
    }
    if (!HAN.test(word)) {
      issues.push({ word, kind: "non-han-title", tag });
      continue;
    }
    const key = `${word}\t${kind}`;
    if (rows.has(key)) continue;
    tags.set(tag, (tags.get(tag) ?? 0) + 1);
    rows.set(key, [word, kind]);
  }
  return ok({ rows: [...rows.values()].sort(compareRows), issues, tags, known: inLexicons });
};

