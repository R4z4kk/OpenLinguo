import { gunzipSync } from "node:zlib";
import { err, ok, parseWith, type Result } from "@openlinguo/core";
import { z } from "zod";
import type { Dataset, ShardReader } from "../run.ts";
import { toShards } from "../shards.ts";
import { readTar } from "../tar.ts";
import { decodeUtf8 } from "./graded.ts";

const PACKAGE = "hanzi-writer-data@2.0.1";
const REFERENTIALS = ["hsk-2025-chars", "gf0025-2021-chars"];
const MAX_REPORTED = 10;
const SHARD_SIZE = 1_000;

const CharacterShard = z.array(z.tuple([z.string(), z.number()]));

const Strokes = z
  .object({
    strokes: z.array(z.string().min(1)).min(1),
    medians: z.array(z.array(z.tuple([z.number(), z.number()])).min(1)),
    radStrokes: z.array(z.number().int().nonnegative()).default([]),
  })
  .refine(
    ({ strokes, medians, radStrokes }) =>
      medians.length === strokes.length && radStrokes.every((index) => index < strokes.length),
  );

/** `[character, SVG stroke paths, stroke medians, radical stroke indexes]` in the hanzi-writer format. */
export type StrokeRow = readonly [
  character: string,
  strokes: readonly string[],
  medians: readonly (readonly (readonly [number, number])[])[],
  radStrokes: readonly number[],
];

/** Characters of the graded referentials, in order, without duplicates. */
const loadCharacters = async (
  readShards: ShardReader,
): Promise<Result<readonly string[], string>> => {
  const characters = new Set<string>();
  for (const dataset of REFERENTIALS) {
    const shards = await readShards(dataset);
    if (!shards.ok) return err(`cannot read ${dataset}: ${shards.error}`);
    if (shards.value.length === 0) return err(`${dataset} must be built before hanzi-writer-data`);
    for (const shard of shards.value) {
      let json: unknown;
      try {
        json = JSON.parse(shard);
      } catch (error) {
        return err(`invalid ${dataset} shard: ${String(error)}`);
      }
      const rows = parseWith(CharacterShard, json);
      if (!rows.ok) return err(`invalid ${dataset} shard structure`);
      for (const [character] of rows.value) characters.add(character);
    }
  }
  return ok([...characters]);
};

const parseStrokes = (bytes: Uint8Array): Result<z.output<typeof Strokes>, string> => {
  const text = decodeUtf8(bytes);
  if (!text.ok) return text;
  try {
    const parsed = parseWith(Strokes, JSON.parse(text.value));
    return parsed.ok ? parsed : err("invalid stroke data");
  } catch (error) {
    return err(String(error));
  }
};

const readme = (summary: string): string => `# hanzi-writer-data — HSK subset

Generated by \`tools/data-pipeline\` from the npm package ${PACKAGE}. Do not edit by hand.

- Source: https://www.npmjs.com/package/hanzi-writer-data (https://github.com/chanind/hanzi-writer-data), by David Chanin, derived from Make Me a Hanzi \`graphics.txt\` (Shaunak Kishore), itself derived from the Arphic PL KaitiM GB and Arphic PL UKai fonts
- License: Arphic Public License, Copyright (C) 1999 Arphic Technology Co., Ltd. (\`ARPHICPL.TXT\`)
- Changes: this data has been modified. Only the characters of the HSK 2025 syllabus and of the GF0025-2021 standard are kept, as JSON shards of \`[character, strokes, medians, radStrokes]\` (hanzi-writer format, 1024-unit box); \`radStrokes\` is empty when the source has none. Characters without stroke data are listed in \`missing.tsv\`.
- Result: ${summary}.
`;

export const hanziWriterData: Dataset = {
  id: "hanzi-writer-data",
  url: "https://registry.npmjs.org/hanzi-writer-data/-/hanzi-writer-data-2.0.1.tgz",
  license: "Arphic-1999",
  maxAgeDays: 365,
  build: async (raw, readShards) => {
    let archive: Uint8Array;
    try {
      archive = gunzipSync(raw);
    } catch (error) {
      return err(`cannot decompress: ${String(error)}`);
    }
    const files = readTar(archive);
    if (!files.ok) return files;
    const licenseBytes = files.value.get("package/ARPHICPL.TXT");
    if (licenseBytes == null) return err("package has no ARPHICPL.TXT");
    const license = decodeUtf8(licenseBytes);
    if (!license.ok) return license;
    const characters = await loadCharacters(readShards);
    if (!characters.ok) return characters;

    const rows: StrokeRow[] = [];
    const missing: string[] = [];
    const invalid: string[] = [];
    for (const character of characters.value) {
      const bytes = files.value.get(`package/${character}.json`);
      if (bytes == null) {
        missing.push(character);
        continue;
      }
      const data = parseStrokes(bytes);
      if (!data.ok) {
        invalid.push(character);
        continue;
      }
      rows.push([character, data.value.strokes, data.value.medians, data.value.radStrokes]);
    }
    if (invalid.length > 0) {
      const shown = invalid.slice(0, MAX_REPORTED).join(" ");
      return err(`${String(invalid.length)} characters with invalid stroke data (${shown})`);
    }
    const summary = `${String(rows.length)} of ${String(characters.value.length)} HSK 2025 and GF0025-2021 characters, ${String(missing.length)} missing`;
    const output = new Map(toShards("strokes", rows, SHARD_SIZE));
    output.set("README.md", readme(summary));
    output.set("ARPHICPL.TXT", license.value);
    output.set("missing.tsv", `${["character", ...missing].join("\n")}\n`);
    return ok({ version: PACKAGE, files: output, summary });
  },
};
