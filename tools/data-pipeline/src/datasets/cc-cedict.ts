import { gunzipSync } from "node:zlib";
import { err, ok, type Result } from "@openlinguo/core";
import type { Dataset } from "../run.ts";
import { toShards } from "../shards.ts";

export type CedictRow = readonly [
  simplified: string,
  traditional: string,
  pinyin: string,
  glosses: readonly string[],
];

export type CedictRelease = { readonly date: string; readonly rows: readonly CedictRow[] };

const ENTRY = /^(\S+) (\S+) \[([^\]]+)\] \/(.+)\/$/u;
const HEADER = /^#! (\w+)=(.*)$/u;
const MAX_REPORTED_LINES = 10;

export const parseCedict = (text: string): Result<CedictRelease, string> => {
  const header = new Map<string, string>();
  const rows: CedictRow[] = [];
  const invalidLines: number[] = [];

  text.split(/\r?\n/u).forEach((line, index) => {
    if (line === "") return;
    if (line.startsWith("#")) {
      const field = HEADER.exec(line);
      if (field?.[1] != null && field[2] != null) header.set(field[1], field[2]);
      return;
    }
    const match = ENTRY.exec(line);
    const glosses = match?.[4]?.split("/") ?? [];
    if (match?.[1] == null || match[2] == null || match[3] == null || glosses.includes("")) {
      invalidLines.push(index + 1);
      return;
    }
    rows.push([match[2], match[1], match[3], glosses]);
  });

  if (invalidLines.length > 0) {
    const shown = invalidLines.slice(0, MAX_REPORTED_LINES).join(", ");
    return err(`${String(invalidLines.length)} malformed entries (lines ${shown})`);
  }
  const date = header.get("date") ?? null;
  const entries = header.get("entries") ?? null;
  if (date === null || entries === null || !/^\d+$/u.test(entries)) {
    return err("release header is missing #! date or #! entries");
  }
  const declared = Number(entries);
  if (rows.length !== declared) {
    return err(`header declares ${String(declared)} entries, parsed ${String(rows.length)}`);
  }
  return ok({ date, rows });
};

const SHARD_SIZE = 10_000;

const readme = (date: string): string => `# CC-CEDICT

Generated by \`tools/data-pipeline\` from the CC-CEDICT release dated ${date}. Do not edit by hand.

- Source: https://www.mdbg.net/chinese/dictionary?page=cc-cedict
- Publisher: MDBG
- License: Creative Commons Attribution-ShareAlike 4.0 International, https://creativecommons.org/licenses/by-sa/4.0/
- Referenced works: CEDICT, Copyright (C) 1997, 1998 Paul Andrew Denisowski
- Changes: converted to JSON shards of \`[simplified, traditional, numbered pinyin, glosses]\`; entries are unchanged.
`;

export const ccCedict: Dataset = {
  id: "cc-cedict",
  url: "https://www.mdbg.net/chinese/export/cedict/cedict_1_0_ts_utf-8_mdbg.txt.gz",
  license: "CC-BY-SA-4.0",
  maxAgeDays: 90,
  build: (raw) => {
    let text: string;
    try {
      text = new TextDecoder("utf-8", { fatal: true }).decode(gunzipSync(raw));
    } catch (error) {
      return err(`cannot decompress or decode: ${String(error)}`);
    }
    const release = parseCedict(text);
    if (!release.ok) return release;
    const files = new Map(toShards("entries", release.value.rows, SHARD_SIZE));
    files.set("README.md", readme(release.value.date));
    return ok({ version: release.value.date, files });
  },
};
