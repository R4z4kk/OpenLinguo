import { readFile } from "node:fs/promises";
import { err, ok, type Result } from "@openlinguo/core";
import { z } from "zod";
import { parseJsonLines } from "../jsonl.ts";
import type { Dataset } from "../run.ts";
import { toShards } from "../shards.ts";
import { decodeUtf8 } from "./graded.ts";

const COMMIT = "bddc96d41bef78427ed0e034e9f7e31d71fd1b92";
const VERSION = `skishore/makemeahanzi@${COMMIT.slice(0, 7)}`;
const LICENSES = ["makemeahanzi-LGPL", "GPL-3.0.txt"];
const SHARD_SIZE = 10_000;

const Text = z.string().nullable().default(null);

const Line = z.object({
  character: z.string().refine((text) => Array.from(text).length === 1),
  decomposition: z.string().min(1),
  radical: z.string().min(1),
  etymology: z
    .object({
      type: z.enum(["ideographic", "pictographic", "pictophonetic"]),
      hint: Text,
      phonetic: Text,
      semantic: Text,
    })
    .nullable()
    .default(null),
});

/** `[character, decomposition (IDS, ？ for an unknown component), radical, etymology]` */
export type DecompositionRow = readonly [
  character: string,
  decomposition: string,
  radical: string,
  etymology: z.output<typeof Line>["etymology"],
];

export const parseDictionary = (text: string): Result<readonly DecompositionRow[], string> => {
  const lines = parseJsonLines(text, Line);
  if (!lines.ok) return lines;
  const rows = lines.value.map((line): DecompositionRow => [
    line.character,
    line.decomposition,
    line.radical,
    line.etymology,
  ]);
  const characters = new Set(rows.map(([character]) => character));
  if (characters.size !== rows.length) {
    return err(`${String(rows.length - characters.size)} duplicate characters`);
  }
  return ok(rows);
};

const readLicenses = async (): Promise<Result<ReadonlyMap<string, string>, string>> => {
  try {
    const texts = await Promise.all(
      LICENSES.map((name) => readFile(new URL(`../../licenses/${name}`, import.meta.url), "utf8")),
    );
    return ok(new Map(LICENSES.map((name, index) => [name, texts[index] ?? ""])));
  } catch (error) {
    return err(`cannot read license texts: ${String(error)}`);
  }
};

const readme = (summary: string): string => `# Make Me a Hanzi — decomposition

Generated by \`tools/data-pipeline\` from ${VERSION}. Do not edit by hand.

- Source: \`dictionary.txt\` of https://github.com/skishore/makemeahanzi at commit ${COMMIT}, derived from Unihan and CJKlib
- Author: Shaunak Kishore
- License: GNU Lesser General Public License 3.0 or later (\`makemeahanzi-LGPL\`, with the Unicode notice for Unihan data; the LGPL incorporates \`GPL-3.0.txt\`)
- Changes: this data has been modified. Converted to JSON shards of \`[character, decomposition, radical, etymology]\`; the \`definition\`, \`pinyin\` and \`matches\` fields are removed (definitions and readings come from CC-CEDICT, radical strokes from hanzi-writer-data). Missing etymology fields are \`null\`.
- Result: ${summary}.
`;

export const makemeahanzi: Dataset = {
  id: "makemeahanzi",
  url: `https://raw.githubusercontent.com/skishore/makemeahanzi/${COMMIT}/dictionary.txt`,
  license: "LGPL-3.0-or-later",
  maxAgeDays: 365,
  build: async (raw) => {
    const text = decodeUtf8(raw);
    if (!text.ok) return text;
    const rows = parseDictionary(text.value);
    if (!rows.ok) return rows;
    const licenses = await readLicenses();
    if (!licenses.ok) return licenses;
    const unknown = rows.value.filter(([, decomposition]) => decomposition.includes("？")).length;
    const summary = `${String(rows.value.length)} characters, ${String(unknown)} with an unknown component`;
    const files = new Map([...toShards("characters", rows.value, SHARD_SIZE), ...licenses.value]);
    files.set("README.md", readme(summary));
    return ok({ version: VERSION, files, summary });
  },
};
