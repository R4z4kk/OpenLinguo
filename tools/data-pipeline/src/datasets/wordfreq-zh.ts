export const wordfreqZh: Dataset = {
  id: "wordfreq-zh",
  url: `https://raw.githubusercontent.com/rspeer/wordfreq/${COMMIT}/wordfreq/data/large_zh.msgpack.gz`,
  license: "CC-BY-SA-4.0",
  maxAgeDays: 365,
  build: async (raw, readShards) => {
    const zipf = parseCBPack(raw);
    if (!zipf.ok) return zipf;
    const headwords = await loadHeadwords(readShards);
    if (!headwords.ok) return headwords;
    const rows = headwordFrequencies(zipf.value, headwords.value);
    const summary = `${String(rows.length)} of ${String(headwords.value.size)} dictionary headwords have a frequency (${String(zipf.value.size)} words in the list)`;
    const files = new Map(toShards("words", rows, SHARD_SIZE));
    files.set("README.md", readme(summary));
    return ok({ version: VERSION, files, summary });
  },
};
