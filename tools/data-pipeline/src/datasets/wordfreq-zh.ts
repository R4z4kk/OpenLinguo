import { gunzipSync } from "node:zlib";
import { err, ok, parseWith, type Result } from "@openlinguo/core";
import { z } from "zod";
import { decodeMsgpack } from "../msgpack.ts";
import type { Dataset, ShardReader } from "../run.ts";
import { toShards } from "../shards.ts";

// wordfreq is frozen (SUNSET.md, 2024): its last data release is pinned as a dataset.
const COMMIT = "912caf64b657478d1dff1138efdc078947d54bb1";
const VERSION = `large_zh, rspeer/wordfreq@${COMMIT.slice(0, 7)}`;
/** Datasets whose rows start with a simplified headword. */
const HEADWORD_DATASETS = ["cc-cedict", "cfdict", "wiktionary-fr-zh"];
const SHARD_SIZE = 50_000;

const CBPack = z
  .tuple([z.object({ format: z.literal("cB"), version: z.literal(1) })])
  .rest(z.array(z.string().min(1)));
const HeadwordShard = z.array(z.tuple([z.string()]).rest(z.unknown()));

/** `[simplified word, Zipf frequency]`: log10 of the occurrences per billion words. */
export type WordFrequency = readonly [string, number];

/**
 * Zipf frequency of each word of a wordfreq cBpack: after the header, bucket `i` holds the
 * words whose frequency is 10^(-i/100), so their Zipf value is 9 - i/100.
 */
export const parseCBPack = (raw: Uint8Array): Result<ReadonlyMap<string, number>, string> => {
  let unzipped: Uint8Array;
  try {
    unzipped = gunzipSync(raw);
  } catch (error) {
    return err(`cannot gunzip: ${String(error)}`);
  }
  const decoded = decodeMsgpack(unzipped);
  if (!decoded.ok) return decoded;
  const pack = parseWith(CBPack, decoded.value);
  if (!pack.ok) return err("not a cB version 1 word list");
  const [, ...buckets] = pack.value;
  const zipf = new Map<string, number>();
  for (const [index, bucket] of buckets.entries()) {
    for (const word of bucket) {
      if (zipf.has(word)) return err(`${word} appears in two buckets`);
      zipf.set(word, (900 - index) / 100);
    }
  }
  return ok(zipf);
};

const loadHeadwords = async (
  readShards: ShardReader,
): Promise<Result<ReadonlySet<string>, string>> => {
  const headwords = new Set<string>();
  for (const dataset of HEADWORD_DATASETS) {
    const shards = await readShards(dataset);
    if (!shards.ok) return err(`cannot read ${dataset}: ${shards.error}`);
    if (shards.value.length === 0) return err(`${dataset} must be built before wordfreq-zh`);
    for (const shard of shards.value) {
      let json: unknown;
      try {
        json = JSON.parse(shard);
      } catch (error) {
        return err(`invalid ${dataset} shard: ${String(error)}`);
      }
      const rows = parseWith(HeadwordShard, json);
      if (!rows.ok) return err(`invalid ${dataset} shard structure`);
      for (const [headword] of rows.value) headwords.add(headword);
    }
  }
  return ok(headwords);
};

/** Frequencies of the dictionary headwords, most frequent first. */
export const headwordFrequencies = (
  zipf: ReadonlyMap<string, number>,
  headwords: ReadonlySet<string>,
): readonly WordFrequency[] =>
  [...zipf]
    .filter(([word]) => headwords.has(word))
    .sort(([a, zipfA], [b, zipfB]) => zipfB - zipfA || (a < b ? -1 : 1));

