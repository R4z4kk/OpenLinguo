import { LIBRARY_PAGE_SIZE, type LibraryItem } from "@openlinguo/core/submission";
import { expect, type Page, type Route } from "@playwright/test";
import { en } from "../src/i18n/en.ts";
import { accessibilityViolations } from "./accessibility.ts";
import { test } from "./app.ts";

const provenance = {
  origin: "ai",
  provider: "groq",
  model: "llama-3.3-70b-versatile",
  promptVersion: "zh-story-v1",
  createdAt: "2026-10-30T09:00:00.000Z",
} as const;

const CAT: LibraryItem = {
  id: "00000000-0000-4000-8000-0000000003a1",
  title: "我的猫",
  body: "我的猫很可爱。\n它喜欢睡觉。",
  attribution: "小明",
  origin: "human",
  provenance: null,
  licence: "CC-BY-SA-4.0",
  band: 2,
  publishedAt: "2026-10-31T12:00:00.000Z",
};
const STORY: LibraryItem = {
  id: "00000000-0000-4000-8000-0000000003a2",
  title: "小花和大雨",
  body: "小花在家。外面下大雨。",
  attribution: null,
  origin: "ai",
  provenance,
  licence: "CC0-1.0",
  band: 1,
  publishedAt: "2026-10-30T12:00:00.000Z",
};
const OLDER: LibraryItem = { ...CAT, id: "00000000-0000-4000-8000-0000000003a3", title: "老师" };

const summary = (item: LibraryItem) =>
  Object.fromEntries(Object.entries(item).filter(([key]) => key !== "body"));

// `vite preview` has no Functions: the API answers here.
type FakeApi = { readonly asked: string[]; offline: boolean };

const fakeApi = async (page: Page): Promise<FakeApi> => {
  const api: FakeApi = { asked: [], offline: false };
  const json = (route: Route, status: number, body: unknown) =>
    route.fulfill({ status, contentType: "application/json", body: JSON.stringify(body) });
  await page.route("**/api/**", async (route) => {
    const url = new URL(route.request().url());
    api.asked.push(`${url.pathname}${url.search}`);
    if (api.offline) {
      await route.abort("internetdisconnected");
      return;
    }
    if (url.pathname === "/api/library") {
      const band = url.searchParams.get("band");
      const all = [CAT, STORY, OLDER].filter((item) => band === null || String(item.band) === band);
      const second = url.searchParams.get("page") === "2";
      const items = band === null ? (second ? [OLDER] : [CAT, STORY]) : all;
      await json(route, 200, {
        items: items.map(summary).slice(0, LIBRARY_PAGE_SIZE),
        nextPage: band === null && !second ? 2 : null,
      });
      return;
    }
    const id = /^\/api\/library\/(.+)$/u.exec(url.pathname)?.[1] ?? null;
    const found = [CAT, STORY, OLDER].find((item) => item.id === id) ?? null;
    if (found !== null) await json(route, 200, found);
    else await json(route, 404, { code: "NOT_FOUND", message: url.pathname });
  });
  return api;
};

const openRead = async (page: Page): Promise<void> => {
  await page.goto("/read");
  await expect(page.getByRole("main").getByText(en.library.emptyTitle)).toBeVisible({
    timeout: 90_000,
  });
};

const press = async (page: Page, name: string): Promise<void> => {
  await page
    .getByRole("main")
    .getByRole("link", { name, exact: true })
    .or(page.getByRole("main").getByRole("button", { name, exact: true }))
    .focus();
  await page.keyboard.press("Enter");
};

test.use({ serviceWorkers: "block" });

test("imports a text from the global library and reads it offline", async ({ page }) => {
  const api = await fakeApi(page);
  await openRead(page);
  expect(api.asked).toEqual([]);
  const main = page.getByRole("main");
  await press(page, en.globalLibrary.link);
  await expect(main.getByRole("heading", { level: 1, name: en.globalLibrary.title })).toBeVisible();
  await expect(main.getByRole("link", { name: CAT.title, exact: true })).toBeVisible();
  await expect(main.getByText("HSK 2 · estimated")).toBeVisible();
  await expect(main.getByText(`Generated by AI · ${provenance.model}`)).toBeVisible();
  await expect(main.getByText("By 小明")).toBeVisible();
  expect(await accessibilityViolations(page)).toEqual([]);

  await press(page, en.globalLibrary.more);
  await expect(main.getByRole("link", { name: OLDER.title, exact: true })).toBeVisible();
  await expect(main.getByRole("button", { name: en.globalLibrary.more })).toHaveCount(0);
  await main.getByRole("combobox", { name: en.globalLibrary.level }).selectOption("2");
  await expect(main.getByRole("link", { name: STORY.title, exact: true })).toHaveCount(0);
  expect(api.asked).toEqual(["/api/library", "/api/library?page=2", "/api/library?band=2"]);

  await press(page, CAT.title);
  await expect(main.getByRole("heading", { level: 1, name: CAT.title })).toBeVisible();
  await expect(main.getByText(/of words known|No Chinese word/u)).toBeVisible();
  await expect(main.getByText(en.submit.human.link)).toBeVisible();
  await expect(main.getByText(/^To reuse it, credit its title, 小明,/u)).toBeVisible();
  expect(await accessibilityViolations(page)).toEqual([]);

  await press(page, `Import « ${CAT.title} »`);
  await expect(main.getByRole("status").getByText(en.globalLibrary.added)).toBeVisible();
  const imported = main.getByRole("button", { name: `« ${CAT.title} » is already in My texts` });
  await expect(imported).toHaveAttribute("aria-disabled", "true");
  await expect(imported).toHaveText(en.globalLibrary.imported);
  expect(await accessibilityViolations(page)).toEqual([]);

  api.offline = true;
  await press(page, en.globalLibrary.open);
  await expect(main.getByRole("heading", { level: 1, name: CAT.title })).toBeVisible();
  await expect(main.getByText(en.library.source.library, { exact: false })).toBeVisible();
  await expect(main.getByRole("link", { name: en.submit.link })).toHaveCount(0);
  await page.goto("/read");
  await expect(main.getByRole("link", { name: CAT.title, exact: true })).toBeVisible({
    timeout: 60_000,
  });
});

test("says the library needs a connection, then loads it on « Try again »", async ({ page }) => {
  const api = await fakeApi(page);
  await openRead(page);
  api.offline = true;
  const main = page.getByRole("main");
  await press(page, en.globalLibrary.link);
  await expect(main.getByRole("alert")).toHaveText(en.globalLibrary.failure.offline);
  await expect(main.getByRole("link", { name: CAT.title, exact: true })).toHaveCount(0);
  expect(await accessibilityViolations(page)).toEqual([]);
  api.offline = false;
  await press(page, en.globalLibrary.retry);
  await expect(main.getByRole("link", { name: CAT.title, exact: true })).toBeVisible();
  await expect(main.getByRole("alert")).toHaveCount(0);
});

test("says when a text is no longer in the library", async ({ page }) => {
  await fakeApi(page);
  await openRead(page);
  await page.goto("/read/library/00000000-0000-4000-8000-0000000003ff");
  await expect(page.getByRole("main").getByRole("alert")).toHaveText(
    en.globalLibrary.failure.notFound,
  );
});
